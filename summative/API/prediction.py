"""
Informal Business Revenue API (Nigeria)

Estimates the monthly revenue per worker of a Nigerian informal business so a lender can size a
loan it can repay. Uses the random forest pipeline trained in linear_regression/multivariate.ipynb.

Routes
  GET  /          service info
  POST /predict   12 business details in, estimated monthly revenue out
  POST /retrain   upload a CSV of new businesses; the model is refitted and used straight away
  GET  /docs      Swagger UI (generated by FastAPI)

Run locally (from summative/API):  uv run uvicorn prediction:app --reload
"""

import copy
import io
import os
import threading
from datetime import datetime, timezone
from pathlib import Path
from typing import Literal

import joblib
import numpy as np
import pandas as pd
from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, ConfigDict, Field, ValidationError
from sklearn.base import clone
from sklearn.linear_model import SGDRegressor
from sklearn.metrics import mean_squared_error

API_DIR = Path(__file__).parent
MODEL_PATH = API_DIR / "best_model.pkl"
TARGET = "revenue_per_worker"
MAX_UPLOAD_BYTES = 5 * 1024 * 1024


# ---------------------------------------------------------------------------
# Model loading and prediction (same logic as section 13 of the notebook)
# ---------------------------------------------------------------------------
def load_bundle(path: Path = MODEL_PATH) -> dict:
    """The saved file: the fitted pipeline plus input names, valid ranges and categories."""
    return joblib.load(path)


def predict_revenue_per_worker(row: dict, bundle: dict) -> float:
    """Predict monthly revenue per worker (PPP $) for ONE business."""
    frame = pd.DataFrame([row], columns=bundle["features"])
    log_prediction = float(bundle["model"].predict(frame)[0])
    return round(float(np.expm1(log_prediction)), 2)  # the model learned log(1 + revenue)


bundle_at_start = load_bundle()
state = {"bundle": bundle_at_start, "version": 1, "updated_at": datetime.now(timezone.utc).isoformat()}
state_lock = threading.Lock()    # stops /predict reading the model halfway through a swap
retrain_lock = threading.Lock()  # stops two retraining jobs running at the same time


# ---------------------------------------------------------------------------
# Request schema: one field per model input, each with a type and a range.
# Ranges and allowed values are what the model saw in training (notebook section 12),
# so anything outside them is refused with a 422 error instead of a made-up number.
# ---------------------------------------------------------------------------
State = Literal[tuple(bundle_at_start["states"])]          # the 37 states in the data
Sector = Literal[tuple(bundle_at_start["sectors"])]        # Agriculture, Manufacturing, Other, Services
Area = Literal[tuple(bundle_at_start["urban_values"])]     # Rural, Urban


class BusinessFeatures(BaseModel):
    model_config = ConfigDict(
        extra="forbid",  # an unknown field is an error, not silently ignored
        json_schema_extra={"examples": [{
            "state": "Lagos", "sector": "Services", "urban": "Urban", "survey_year": 2024,
            "total_workers": 2, "business_age": 6, "owner_education_years": 12, "owner_age_group": 3,
            "owner_female": 1, "separate_premises": 1, "sells_to_firms_or_govt": 0, "credit_difficulty": 1,
        }]},
    )

    state: State = Field(description="Nigerian state where the business operates (e.g. Lagos, Kano, FCT)")
    sector: Sector = Field(description="Agriculture, Manufacturing, Other or Services")
    urban: Area = Field(description="Urban or Rural")
    survey_year: int = Field(ge=2019, le=2024, description="Year of the estimate (data covers 2019 and 2024)")
    total_workers: int = Field(ge=1, le=56, description="Workers including the owner")
    business_age: int = Field(ge=1, le=77, description="Years the business has been running")
    owner_education_years: int = Field(ge=0, le=18, description="Owner's years of schooling")
    owner_age_group: int = Field(ge=1, le=6, description="1=15-24, 2=25-34, 3=35-44, 4=45-54, 5=55-64, 6=65+")
    owner_female: int = Field(ge=0, le=1, description="1 if the main owner is a woman, else 0")
    separate_premises: int = Field(ge=0, le=1, description="1 if the business has its own premises, else 0")
    sells_to_firms_or_govt: int = Field(ge=0, le=1, description="1 if it sells to other firms or government")
    credit_difficulty: int = Field(ge=0, le=1, description="1 if it had difficulty getting credit in the last 12 months")


class TrainingRow(BusinessFeatures):
    """One row of a /retrain CSV: the 12 inputs plus the known monthly revenue per worker.
    Like the survey itself, a new row may leave these four answers blank; the saved pipeline fills
    them with the training median, exactly as in the notebook. /predict still requires every field."""
    model_config = ConfigDict(extra="ignore", json_schema_extra=None)
    business_age: int | None = Field(default=None, ge=1, le=77)
    owner_education_years: int | None = Field(default=None, ge=0, le=18)
    owner_age_group: int | None = Field(default=None, ge=1, le=6)
    credit_difficulty: int | None = Field(default=None, ge=0, le=1)
    revenue_per_worker: float = Field(gt=0, le=1_000_000)


class PredictionResponse(BaseModel):
    revenue_per_worker_ppp: float
    business_monthly_revenue_ppp: float
    currency: str
    model: str
    model_version: int


class RetrainResponse(BaseModel):
    message: str
    rows_received: int
    training_rows_total: int
    test_mse_before: float
    test_mse_after: float
    model_version: int
    updated_at: str


# ---------------------------------------------------------------------------
# App and CORS
# ---------------------------------------------------------------------------
app = FastAPI(
    title="Informal Business Revenue API (Nigeria)",
    description=(
        "Estimates the monthly revenue per worker of a Nigerian informal business from 12 facts an owner "
        "can answer, so a lender can size an affordable loan without bank records. Trained on the World Bank "
        "LSMS Household Business Indicators (Nigeria GHS-Panel 2018/19 and 2023/24)."
    ),
    version="1.0.0",
)

# CORS controls which WEBSITES (browser origins) may call this API from their JavaScript.
# - Origins: only this API's own Render address (so Swagger at /docs works) and the local addresses
#   used in development (Swagger on port 8000, Flutter web debug on port 5000). No "*": any other
#   website calling the API from a visitor's browser is blocked, so nobody can build a site on top of
#   our model and use up the free server's limited capacity.
# - Methods: GET and POST only, because those are the only methods the routes use.
# - Headers: Content-Type (JSON bodies and file uploads) and Accept. Nothing else is needed.
# - Credentials: False. The API has no cookies or login, so browsers must not send any.
# The Flutter app on a phone or emulator is not a browser, so CORS does not apply to it.
ALLOWED_ORIGINS = [
    "https://ng-business-revenue-api.onrender.com",
    "http://localhost:8000",
    "http://127.0.0.1:8000",
    "http://localhost:5000",
    "http://127.0.0.1:5000",
]
app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Accept"],
    allow_credentials=False,
)


# ---------------------------------------------------------------------------
# Training data for /retrain.
# The World Bank licence does not allow the survey rows in the public repository, so they are read
# from a private location: Render Secret Files (/etc/secrets) on the server, or the notebook's local
# data/ folder on a laptop. RETRAIN_DATA_DIR can point somewhere else.
# ---------------------------------------------------------------------------
def find_training_files():
    candidates = [os.environ.get("RETRAIN_DATA_DIR"), "/etc/secrets", str(API_DIR.parent / "linear_regression" / "data")]
    for folder in filter(None, candidates):
        train, test = Path(folder) / "train_clean.csv", Path(folder) / "test_clean.csv"
        if train.exists() and test.exists():
            return train, test
    return None


training = {"train": None, "test": None}  # loaded on first /retrain, then kept in memory


def get_training_data():
    if training["train"] is None:
        files = find_training_files()
        if files is None:
            raise HTTPException(status_code=503, detail="Retraining data is not configured on this server.")
        training["train"], training["test"] = pd.read_csv(files[0]), pd.read_csv(files[1])
    return training["train"], training["test"]


# ---------------------------------------------------------------------------
# Routes
# ---------------------------------------------------------------------------
@app.api_route("/", methods=["GET", "HEAD"], tags=["info"])  # HEAD lets uptime checks ping it
def root():
    with state_lock:
        bundle, version, updated = state["bundle"], state["version"], state["updated_at"]
    return {"service": "Informal Business Revenue API (Nigeria)", "docs": "/docs", "model": bundle["model_name"],
            "model_version": version, "updated_at": updated, "inputs": bundle["features"]}


@app.post("/predict", response_model=PredictionResponse, tags=["prediction"])
def predict(business: BusinessFeatures):
    """Estimate monthly revenue per worker, and for the whole business, in PPP US dollars."""
    with state_lock:
        bundle, version = state["bundle"], state["version"]
    per_worker = predict_revenue_per_worker(business.model_dump(), bundle)
    return PredictionResponse(
        revenue_per_worker_ppp=per_worker,
        business_monthly_revenue_ppp=round(per_worker * business.total_workers, 2),
        currency="PPP-adjusted US dollars per month",
        model=bundle["model_name"],
        model_version=version,
    )


@app.post("/retrain", response_model=RetrainResponse, tags=["retraining"])
def retrain(file: UploadFile = File(description="CSV with the 12 input columns plus revenue_per_worker")):
    """Uploading the file triggers retraining; /predict uses the new model as soon as this returns.
    Declared with `def`, so FastAPI runs it in a worker thread and /predict keeps answering meanwhile."""
    if not (file.filename or "").lower().endswith(".csv"):
        raise HTTPException(status_code=400, detail="Please upload a .csv file.")
    raw = file.file.read(MAX_UPLOAD_BYTES + 1)
    if len(raw) > MAX_UPLOAD_BYTES:
        raise HTTPException(status_code=413, detail="File is larger than 5 MB.")
    try:
        new = pd.read_csv(io.BytesIO(raw))
    except Exception:
        raise HTTPException(status_code=400, detail="Could not read the file as CSV.")

    with state_lock:
        bundle = state["bundle"]
    features = bundle["features"]
    missing = [c for c in features + [TARGET] if c not in new.columns]
    if missing:
        raise HTTPException(status_code=400, detail=f"CSV is missing columns: {missing}")
    if new.empty:
        raise HTTPException(status_code=400, detail="CSV has no rows.")

    # every row must pass the same rules as /predict
    errors, rows = [], []
    for line, record in enumerate(new[features + [TARGET]].to_dict(orient="records"), start=2):
        record = {k: (None if pd.isna(v) else v) for k, v in record.items()}  # empty CSV cell -> None
        try:
            rows.append(TrainingRow(**record).model_dump())
        except ValidationError as exc:
            first = exc.errors()[0]
            errors.append(f"row {line}, column '{first['loc'][0]}': {first['msg']}")
    if errors:
        raise HTTPException(status_code=422, detail={"invalid_rows": len(errors), "examples": errors[:10]})
    new_rows = pd.DataFrame(rows)[features + [TARGET]]

    if not retrain_lock.acquire(blocking=False):
        raise HTTPException(status_code=409, detail="A retraining job is already running. Try again shortly.")
    try:
        train, test = get_training_data()
        old_model = bundle["model"]
        y_test = np.log1p(test[TARGET])
        mse_before = mean_squared_error(y_test, old_model.predict(test[features]))

        all_train = pd.concat([train, new_rows], ignore_index=True)
        if isinstance(old_model.named_steps["model"], SGDRegressor):
            # gradient-descent model: copy it, keep the learned weights, continue training on the new rows
            new_model = copy.deepcopy(old_model)
            X_new = new_model.named_steps["prep"].transform(new_rows[features])
            new_model.named_steps["model"].partial_fit(X_new, np.log1p(new_rows[TARGET]))
        else:
            # forest / tree / closed form: refit from scratch on original + new rows with the same settings
            new_model = clone(old_model).fit(all_train[features], np.log1p(all_train[TARGET]))

        mse_after = mean_squared_error(y_test, new_model.predict(test[features]))
        with state_lock:  # swap the live model: the next /predict uses it, no redeploy needed
            state["bundle"] = {**bundle, "model": new_model, "test_mse": float(mse_after)}
            state["version"] += 1
            state["updated_at"] = datetime.now(timezone.utc).isoformat()
            version, updated = state["version"], state["updated_at"]
        training["train"] = all_train
        # The retrained model lives in memory only. Every start loads best_model.pkl from the repository,
        # as the brief asks (Render's free plan resets the disk when the service sleeps anyway).
    finally:
        retrain_lock.release()

    return RetrainResponse(
        message=f"Model retrained on {len(all_train):,} rows and now serving predictions.",
        rows_received=len(new_rows),
        training_rows_total=len(all_train),
        test_mse_before=round(float(mse_before), 4),
        test_mse_after=round(float(mse_after), 4),
        model_version=version,
        updated_at=updated,
    )
